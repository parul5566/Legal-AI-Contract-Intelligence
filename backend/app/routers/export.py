"""Self-contained HTML export of a document analysis."""
import html

from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import HTMLResponse
from sqlalchemy.orm import Session

from app.deps import get_current_user, get_db, get_doc_or_404
from app.engine.taxonomy import category_label, risk_label
from app.models import Clause, Document, RiskFinding, User

router = APIRouter(prefix="/api/documents", tags=["export"])

SEV_COLORS = {
    "low": "#3b82f6", "medium": "#f59e0b", "high": "#ef4444", "critical": "#7f1d1d",
}


def _esc(s) -> str:
    return html.escape(str(s or ""))


def _ul(items) -> str:
    if not items:
        return "<p class='muted'>None</p>"
    return "<ul>" + "".join(f"<li>{_esc(i)}</li>" for i in items) + "</ul>"


@router.get("/{doc_id}/export")
def export_document(
    doc_id: int,
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    doc: Document = get_doc_or_404(db, doc_id, user)
    if doc.status != "ready":
        raise HTTPException(status_code=409, detail="Document not analyzed yet")

    clauses = (
        db.query(Clause).filter(Clause.document_id == doc.id).order_by(Clause.char_start).all()
    )
    risks = db.query(RiskFinding).filter(RiskFinding.document_id == doc.id).all()
    sev_order = {"critical": 0, "high": 1, "medium": 2, "low": 3}  # critical first
    risks = sorted(
        risks, key=lambda r: -sev_order.get(r.severity, 0)
    )
    summary = doc.summary

    clause_rows = "".join(
        f"""<tr><td>{_esc(category_label(c.category))}</td>
            <td>{_esc(c.title)}</td><td>Page {c.page}</td>
            <td>{_esc(c.text[:500])}{'…' if len(c.text) > 500 else ''}</td>
            <td>{c.confidence:.0%}</td><td>{_esc(c.review_status)}</td></tr>"""
        for c in clauses
    )
    risk_rows = "".join(
        f"""<tr><td><span class="sev" style="background:{SEV_COLORS.get(r.severity, '#666')}">
            {_esc(r.severity.upper())}</span></td>
            <td>{_esc(risk_label(r.category))}</td><td>{_esc(r.title)}</td>
            <td>{_esc(r.explanation)}</td><td>{_esc(r.suggestion)}</td>
            <td>{_esc(r.review_status)}</td></tr>"""
        for r in risks
    )

    summary_html = ""
    if summary:
        summary_html = f"""
        <h2>AI Summary — Health Score: {summary.health_score}/100 ({_esc(summary.health_verdict)})</h2>
        <p>{_esc(summary.executive)}</p>
        <h3>Key Obligations</h3>{_ul(summary.key_obligations)}
        <h3>Important Dates</h3>{_ul(summary.important_dates)}
        <h3>Payments</h3>{_ul(summary.payments)}
        <h3>Major Risks</h3>{_ul(summary.major_risks)}
        <h3>Termination</h3><p>{_esc(summary.termination)}</p>
        <h3>Restrictions</h3>{_ul(summary.restrictions)}
        <h3>Compliance</h3>{_ul(summary.compliance)}
        """

    parties = ", ".join(_esc(p) for p in (doc.parties or [])) or "—"
    page_html = f"""<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>Analysis — {_esc(doc.original_name)}</title>
<style>
body{{font-family:Georgia,serif;max-width:1000px;margin:24px auto;padding:0 16px;color:#1a2332}}
h1{{border-bottom:3px solid #1a2332;padding-bottom:8px}} h2{{margin-top:28px}}
table{{border-collapse:collapse;width:100%;font-size:13px}}
td,th{{border:1px solid #cbd5e1;padding:6px 8px;vertical-align:top;text-align:left}}
th{{background:#1a2332;color:#fff}}
.sev{{color:#fff;padding:2px 8px;border-radius:3px;font-size:11px;font-weight:700}}
.muted{{color:#64748b}}
.meta{{background:#f1f5f9;padding:12px;border-radius:6px;font-size:14px}}
.banner{{background:#fef3c7;border:1px solid #f59e0b;padding:10px;border-radius:6px;font-size:13px;margin:12px 0}}
@media print{{.noprint{{display:none}}}}
</style></head><body>
<h1>Contract Analysis Report</h1>
<div class="meta">
<b>Document:</b> {_esc(doc.original_name)} &nbsp;|&nbsp; <b>Type:</b> {_esc(doc.doc_type or '—')}<br>
<b>Parties:</b> {parties} &nbsp;|&nbsp; <b>Jurisdiction:</b> {_esc(doc.jurisdiction or '—')}<br>
<b>Effective:</b> {_esc(doc.effective_date or '—')} &nbsp;|&nbsp; <b>Pages:</b> {doc.page_count} &nbsp;|&nbsp;
<b>Generated:</b> {_esc(doc.analyzed_at)}
</div>
<div class="banner">AI-generated analysis for decision support. Not legal advice —
review all findings with qualified counsel before acting.</div>
<h2>Risk Findings ({len(risks)})</h2>
<table><tr><th>Severity</th><th>Category</th><th>Finding</th><th>Explanation</th>
<th>Suggested Review</th><th>Status</th></tr>{risk_rows}</table>
<h2>Extracted Clauses ({len(clauses)})</h2>
<table><tr><th>Category</th><th>Title</th><th>Location</th><th>Text</th><th>Confidence</th>
<th>Review</th></tr>{clause_rows}</table>
{summary_html}
<p class="muted">Generated by Legal AI Contract Intelligence.</p>
</body></html>"""
    return HTMLResponse(
        content=page_html,
        headers={
            "Content-Disposition": f'inline; filename="analysis-{doc.id}.html"'
        },
    )
